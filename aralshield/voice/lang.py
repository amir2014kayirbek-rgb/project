"""Языковые помощники: даты, падежные окончания после чисел (KK), согласование числительных (RU).

Казахские окончания выбираются по последнему произносимому числительному
(сингармонизм и уподобление согласных); перед запуском — вычитка носителем (раздел 25.4).
"""
from __future__ import annotations

from datetime import date

MONTHS = {
    "ru": ["января", "февраля", "марта", "апреля", "мая", "июня", "июля", "августа", "сентября", "октября",
           "ноября", "декабря"],
    "kk": ["қаңтар", "ақпан", "наурыз", "сәуір", "мамыр", "маусым", "шілде", "тамыз", "қыркүйек", "қазан",
           "қараша", "желтоқсан"],
}
WEEKDAYS = {
    "ru": ["понедельник", "вторник", "среда", "четверг", "пятница", "суббота", "воскресенье"],
    "kk": ["дүйсенбі", "сейсенбі", "сәрсенбі", "бейсенбі", "жұма", "сенбі", "жексенбі"],
}

# Последнее числительное: (слово, класс конечного звука, переднерядный ли гласный)
#   класс: "v" — гласный/звонкий/сонорный (-дан/-ден), "n" — н, м, ң (-нан/-нен), "t" — глухой (-тан/-тен)
_KK_NUM = {
    0: ("нөл", "v", True), 1: ("бір", "v", True), 2: ("екі", "v", True), 3: ("үш", "t", True),
    4: ("төрт", "t", True), 5: ("бес", "t", True), 6: ("алты", "v", False), 7: ("жеті", "v", True),
    8: ("сегіз", "v", True), 9: ("тоғыз", "v", False),
    10: ("он", "n", False), 20: ("жиырма", "v", False), 30: ("отыз", "v", False), 40: ("қырық", "t", False),
    50: ("елу", "v", True), 60: ("алпыс", "t", False), 70: ("жетпіс", "t", True), 80: ("сексен", "n", True),
    90: ("тоқсан", "n", False), 100: ("жүз", "v", True), 1000: ("мың", "n", False),
}
_VOWELS = set("аәеиоөұүыіэюяу")


def _kk_last(n: int) -> tuple[str, str, bool]:
    n = abs(int(n))
    if n == 0:
        return _KK_NUM[0]
    if n % 10:
        return _KK_NUM[n % 10]
    if n % 100:
        return _KK_NUM[n % 100]
    if n % 1000:
        return _KK_NUM[100]
    return _KK_NUM[1000]


def kk_abl(n: int) -> str:
    """Окончание исходного падежа после числа: 7-ден, 4-тен, 10-нан, 20-дан."""
    _, cls, front = _kk_last(n)
    return {"v": "ден" if front else "дан", "n": "нен" if front else "нан", "t": "тен" if front else "тан"}[cls]


def kk_poss(n: int) -> str:
    """Притяжательное окончание 3-го лица после числа («10 ескертудің 7-сі»): 7-сі, 5-і, 6-сы, 10-ы."""
    word, _, front = _kk_last(n)
    if word[-1] in _VOWELS and word[-1] != "у":
        return "сі" if front else "сы"
    return "і" if front else "ы"


def plural_ru(n: int, one: str, few: str, many: str) -> str:
    """Форма слова после числа: 1 день, 2 дня, 5 дней, 21 день."""
    n = abs(int(n))
    if n % 10 == 1 and n % 100 != 11:
        return one
    if 2 <= n % 10 <= 4 and not 12 <= n % 100 <= 14:
        return few
    return many


def date_text(d: date, lang: str, weekday: bool = True) -> str:
    """«29 октября (четверг)» / «29 қазан (бейсенбі)»."""
    s = f"{d.day} {MONTHS[lang][d.month - 1]}"
    return f"{s} ({WEEKDAYS[lang][d.weekday()]})" if weekday else s
